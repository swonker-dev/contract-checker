def configure_document(document: Document) -> None:
    section = document.sections[0]
    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)
    section.left_margin = Inches(0.85)
    section.right_margin = Inches(0.85)

    normal = document.styles["Normal"]
    normal.font.name = "Arial"
    normal.font.size = Pt(10.5)
    normal.font.color.rgb = RGBColor(0, 0, 0)
    normal._element.rPr.rFonts.set(qn("w:ascii"), "Arial")
    normal._element.rPr.rFonts.set(qn("w:hAnsi"), "Arial")

    title = document.styles["Title"]
    title.font.name = "Arial"
    title.font.size = Pt(18)
    title.font.bold = True
    title.font.color.rgb = RGBColor(0, 0, 0)
    title._element.rPr.rFonts.set(qn("w:ascii"), "Arial")
    title._element.rPr.rFonts.set(qn("w:hAnsi"), "Arial")

    heading = document.styles["Heading 1"]
    heading.font.name = "Arial"
    heading.font.size = Pt(12)
    heading.font.bold = True
    heading.font.color.rgb = RGBColor(0, 0, 0)
    heading._element.rPr.rFonts.set(qn("w:ascii"), "Arial")
    heading._element.rPr.rFonts.set(qn("w:hAnsi"), "Arial")
    heading.paragraph_format.space_before = Pt(9)
    heading.paragraph_format.space_after = Pt(4)


def section_title(section_number: str, name: str, style: int) -> str:
    major = section_number.split(".", 1)[0]
    if style == 2:
        return f"Раздел {major} {name}"
    if style == 3:
        return f"{major}  {name.upper()}"
    return f"{major}. {name}"


def build(case: Contract) -> Path:
    document = Document()
    configure_document(document)

    title = document.add_paragraph("Трудовой договор", style="Title")
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title.paragraph_format.space_after = Pt(2)
    number = document.add_paragraph(f"№ {case.number}")
    number.alignment = WD_ALIGN_PARAGRAPH.CENTER
    number.paragraph_format.space_after = Pt(8)

    place_and_date = document.add_paragraph()
    place_and_date.add_run(case.city).bold = True
    place_and_date.add_run(f", {case.date}")
    place_and_date.paragraph_format.space_after = Pt(8)

    intro = document.add_paragraph(
        f"{case.employer}, именуемое в дальнейшем «Работодатель», и {case.employee}, "
        f"именуемый в дальнейшем «Работник», заключили настоящий трудовой договор."
    )
    intro.paragraph_format.line_spacing = 1.08
    intro.paragraph_format.space_after = Pt(8)

    current_major = None
    for clause_id, label, text in case.clauses:
        major = clause_id.split(".", 1)[0]
        if major != current_major:
            document.add_paragraph(section_title(clause_id, label, case.heading_style), style="Heading 1")
            current_major = major
        paragraph = document.add_paragraph()
        paragraph.paragraph_format.first_line_indent = Inches(0.28)
        paragraph.paragraph_format.space_after = Pt(4)
        paragraph.paragraph_format.line_spacing = 1.08
        run = paragraph.add_run(f"{clause_id}{')' if case.heading_style == 3 else ''} ")
        run.bold = True
        paragraph.add_run(text)

    document.add_paragraph("Работодатель: ____________________")
    document.add_paragraph("Работник: ____________________")

    document.core_properties.title = "Трудовой договор"
    document.core_properties.author = "Contract Checker MVP"
    output = OUTPUT_ROOT / case.category / case.filename
    output.parent.mkdir(parents=True, exist_ok=True)
    document.save(output)
    return output


def main() -> None:
    paths = [build(case) for case in CASES]
    print(f"Создано договоров: {len(paths)}")
    for path in paths:
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
